// What the generated mounts -- the photographs by date, the library by tag,
// the trash, the playlists -- answer the same way, in one place rather than
// four (#279, #359).
//
// All of them are views of the index served as collections, all of them
// refuse every write, and since the browser half took the GETs none of them
// serves bytes either. Three of the four are a tree -- a feature package's
// Resolve and Children over nodes that each hold a db.File -- and those are
// one mount written once below; the playlists keep a filesystem of their own,
// because what they list is generated bytes rather than rows, and share the
// gate in front of it.

// errNoBytesHere is what a read of a generated resource is. Reaching it means
// the mount was wired without the browser half in front of it, which is a
// wiring mistake and says so.
var errNoBytesHere = errors.New("dav: these bytes are served by the browser half of this address")

// generatedMethods is what every generated address answers, which is not what
// this half answers: GET and HEAD are the browser's, and saying otherwise
// would make a client believe the collection is listing-only.
const generatedMethods = "OPTIONS, GET, HEAD, PROPFIND"

// gate is the front of every generated mount: the owner the wrapper put on
// the request, OPTIONS answered as class 1, every method but PROPFIND refused,
// and a PROPFIND for the whole tree refused before the library sees it. It
// reports whether the request got through, having answered it when not.
func gate(w http.ResponseWriter, r *http.Request, what string) (owner string, ok bool) {
	owner, ok = auth.User(r.Context())
	if !ok {
		// The wrapper in front of this handler is what puts a user on the
		// request; getting here without one is a routing mistake.
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return "", false
	}

	switch r.Method {
	case http.MethodOptions:
		w.Header().Set("DAV", "1")
		w.Header().Set("Allow", generatedMethods)
		w.WriteHeader(http.StatusOK)
		return "", false
	case "PROPFIND":
	default:
		w.Header().Set("Allow", generatedMethods)
		http.Error(w, what+" is read-only here", http.StatusMethodNotAllowed)
		return "", false
	}
	if refuseInfiniteDepth(w, r) {
		return "", false
	}
	return owner, true
}

// entry is what one node of a generated tree says about itself: what it is
// called inside its parent, whether it is a folder, and the row behind it --
// the zero row for a folder, which has none.
type entry interface {
	Base() string
	IsDir() bool
	File() db.File
}

// tree is a generated tree for the length of one request, which is the shape
// internal/timeline, internal/music and internal/trash each already have.
type tree[N any] interface {
	Resolve(ctx context.Context, name string) (N, error)
	Children(ctx context.Context, n N) ([]N, error)
}

// mount is one generated collection: what it is called in a refusal and a
// log line, how one request's tree is opened for the owner, and how a node
// of it is read as an entry.
type mount[N any] struct {
	what  string
	open  func(ctx context.Context, owner string) tree[N]
	entry func(N) entry
}

// handler serves the mount under prefix.
//
// Two things are easy to get wrong here, and both are handled below:
//
//   - x/net opens every resource a PROPFIND lists, to ask it for dead
//     properties. A month of a thousand photographs would then be a thousand
//     reads from the blob store to answer a listing -- which is why nothing
//     under this handler reads bytes at all, and why each tree caches what it
//     has already looked up.
//   - x/net answers 404 for any error opening a file, so the request is
//     resolved before it sees it and a broken database is a 500 rather than
//     a client being told its photographs are gone.
func (m mount[N]) handler(prefix string) http.Handler {
	prefix = strings.TrimSuffix(prefix, "/")
	// x/net's own and not the table the file surface uses (#243): nothing here
	// writes, so no lock taken on this mount can ever refuse anything, and one
	// that outlived the process would be state kept for a surface that has
	// none.
	locks := xnet.NewMemLS()

	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		owner, ok := gate(w, r, m.what)
		if !ok {
			return
		}

		gfs := &generatedFS[N]{ctx: r.Context(), tree: m.open(r.Context(), owner), entry: m.entry}
		n, err := gfs.tree.Resolve(r.Context(), strings.TrimPrefix(r.URL.Path, prefix))
		if err == nil && m.entry(n).IsDir() && r.Header.Get("Depth") == "1" {
			_, err = gfs.tree.Children(r.Context(), n)
		}
		switch {
		case errors.Is(err, os.ErrNotExist):
			http.NotFound(w, r)
			return
		case err != nil:
			slog.ErrorContext(r.Context(), "dav: cannot read "+m.what, "err", err)
			http.Error(w, "the server could not read "+m.what, http.StatusInternalServerError)
			return
		}

		(&xnet.Handler{Prefix: prefix, FileSystem: gfs, LockSystem: locks}).ServeHTTP(w, r)
	})
}

// generatedFS is x/net's FileSystem over one request's view of a tree. The
// view itself -- what is where, and what it is called -- is the feature
// package's; what is here is the shape x/net asks for.
type generatedFS[N any] struct {
	refusesWrites
	// ctx is the request's, for the calls x/net's File interface gives no
	// context to.
	ctx   context.Context
	tree  tree[N]
	entry func(N) entry
}

func (g *generatedFS[N]) Stat(ctx context.Context, name string) (os.FileInfo, error) {
	n, err := g.tree.Resolve(ctx, name)
	if err != nil {
		return nil, err
	}
	return entryInfo{e: g.entry(n)}, nil
}

func (g *generatedFS[N]) OpenFile(ctx context.Context, name string, flag int, _ os.FileMode) (xnet.File, error) {
	if flag != os.O_RDONLY {
		return nil, errReadOnly
	}
	n, err := g.tree.Resolve(ctx, name)
	if err != nil {
		return nil, err
	}
	return &generatedFile[N]{fs: g, node: n}, nil
}

// generatedFile is what OpenFile hands back, and it has no bytes in it: a
// PROPFIND opens every resource it lists and reads none of them, and a GET is
// the other half's. A read here would mean this handler had been mounted
// without that half, which is a wiring mistake and says so.
type generatedFile[N any] struct {
	noBytes
	fs   *generatedFS[N]
	node N
	read bool
}

func (f *generatedFile[N]) Readdir(count int) ([]os.FileInfo, error) {
	if !f.fs.entry(f.node).IsDir() {
		return nil, errReadOnly
	}
	if f.read && count > 0 {
		return nil, nil
	}
	f.read = true
	children, err := f.fs.tree.Children(f.fs.ctx, f.node)
	if err != nil {
		return nil, err
	}
	out := make([]os.FileInfo, 0, len(children))
	for _, c := range children {
		out = append(out, entryInfo{e: f.fs.entry(c)})
	}
	return out, nil
}

func (f *generatedFile[N]) Stat() (os.FileInfo, error) { return entryInfo{e: f.fs.entry(f.node)}, nil }

// entryInfo is x/net's FileInfo, ETager and ContentTyper for one generated
// resource: the original's own validator and type, for the reasons rowInfo
// gives, and the file's own modification time rather than anything about
// when it was listed or deleted -- a copy taken out of here is the file.
type entryInfo struct {
	noSys
	e entry
}

func (i entryInfo) Name() string { return i.e.Base() }
func (i entryInfo) IsDir() bool  { return i.e.IsDir() }

func (i entryInfo) Size() int64 {
	if i.e.IsDir() {
		return 0
	}
	return i.e.File().Size
}

func (i entryInfo) ModTime() time.Time {
	if i.e.IsDir() {
		return time.Time{}
	}
	return i.e.File().MTime
}

func (i entryInfo) Mode() os.FileMode {
	if i.e.IsDir() {
		return fs.ModeDir | 0o555
	}
	return 0o444
}

func (i entryInfo) ContentType(context.Context) (string, error) {
	if i.e.IsDir() {
		return "httpd/unix-directory", nil
	}
	return cmp.Or(i.e.File().MIMEType, "application/octet-stream"), nil
}

func (i entryInfo) ETag(context.Context) (string, error) {
	if i.e.IsDir() || i.e.File().ETag == "" {
		return "", xnet.ErrNotImplemented
	}
	return strconv.Quote(i.e.File().ETag), nil
}

// refusesWrites is the writing half of x/net's FileSystem.
type refusesWrites struct{}

func (refusesWrites) Mkdir(context.Context, string, os.FileMode) error { return errReadOnly }
func (refusesWrites) RemoveAll(context.Context, string) error          { return errReadOnly }
func (refusesWrites) Rename(context.Context, string, string) error     { return errReadOnly }

// noBytes is the reading half of x/net's File, for a resource whose bytes are
// served elsewhere.
type noBytes struct{}

func (noBytes) Read([]byte) (int, error)       { return 0, errNoBytesHere }
func (noBytes) Seek(int64, int) (int64, error) { return 0, errNoBytesHere }
func (noBytes) Write([]byte) (int, error)      { return 0, errReadOnly }
func (noBytes) Close() error                   { return nil }

// noSys is os.FileInfo's escape hatch, which nothing here has anything to put
// in.
type noSys struct{}

func (noSys) Sys() any { return nil }
